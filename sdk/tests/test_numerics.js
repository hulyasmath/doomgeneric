"use strict";
const assert = require("node:assert/strict");
const N = require("../zeq-numerics.js");
function ok(result) { assert.equal(result.status, "ok", `${result.method}: ${result.error}`); assert.equal(result.format, N.FORMAT); assert.equal(result.profile, N.PROFILE); return result; }
const weights = ok(N.finiteDifferenceWeights([-1, 0, 1], 1));
assert.ok(weights.value.every((value, i) => Math.abs(value - [-0.5, 0, 0.5][i]) < 1e-14));
assert.ok(weights.residualInfNorm < 1e-14);
assert.equal(N.finiteDifferenceWeights([0, 0, 1], 1).status, "invalid-input");
const convergence = ok(N.finiteDifferenceConvergence(Math.exp, 0, { exact: 1, levels: 8 }));
assert.ok(Math.abs(convergence.finalEstimate - 1) < 2e-5);
assert.ok(convergence.value.at(-1).observedOrder > 1.7);
const odeOptions = { end: 1, absoluteTolerance: 1e-9, relativeTolerance: 1e-9, recordSteps: true, maxMilliseconds: 60000 };
const ode = ok(N.integrateOde((t, y) => y, { t: 0, y: [1] }, odeOptions));
assert.ok(Math.abs(ode.value.y[0] - Math.E) < 1e-6);
assert.ok(ode.acceptedSteps > 0 && ode.evaluations >= ode.acceptedSteps * 7);
assert.equal(ode.value.t, 1);
const odeRepeat = ok(N.integrateOde((t, y) => y, { t: 0, y: [1] }, odeOptions));
assert.deepEqual(ode.value, odeRepeat.value);
assert.deepEqual(ode.steps, odeRepeat.steps);
assert.equal(N.integrateOde((t, y) => y, { t: 0, y: [1] }, { end: 1, maxSteps: 1 }).status, "budget-exceeded");
assert.equal(N.integrateOde(() => [NaN], { t: 0, y: [1] }, { end: 1 }).status, "invalid-input");
const area = ok(N.quadrature(Math.sin, 0, Math.PI));
assert.ok(Math.abs(area.value - 2) < 1e-8 && area.errorEstimate < 1e-8);
assert.equal(N.quadrature(x => 1 / x, 0, 1).status, "invalid-input");
assert.equal(N.quadrature(x => x === 0 ? 0 : 1 / x, 0, 1, { maxDepth: 8 }).status, "diverged");
const sum = ok(N.compensatedSum([1e16, 1, -1e16]));
assert.equal(sum.value, 1);
const series = ok(N.sumSeries(i => 2 ** -i, { start: 0, tolerance: 1e-12 }));
assert.ok(Math.abs(series.value - 2) < 1e-11 && series.tailEstimate <= 1e-12);
assert.equal(N.sumSeries(i => 1 / (i + 1), { maxTerms: 100 }).status, "budget-exceeded");
const root = ok(N.rootBracketed(x => x * x - 2, [0, 2]));
assert.ok(Math.abs(root.value - Math.SQRT2) < 1e-10 && Math.abs(root.residual) < 1e-9);
assert.equal(N.rootBracketed(x => x * x + 1, [-1, 1]).status, "refused");
const linear = ok(N.solveLinear([[3, 2], [1, 2]], [5, 5]));
assert.ok(linear.value.every((value, i) => Math.abs(value - [0, 2.5][i]) < 1e-12));
assert.ok(linear.residualInfNorm < 1e-12 && linear.conditionInfNorm > 1);
assert.equal(N.solveLinear([[1, 2], [2, 4]], [1, 2]).status, "singular");
assert.equal(N.solveLinear([[1, 2]], [1]).status, "invalid-input");
const eigen = ok(N.symmetricEigen([[2, 1], [1, 2]]));
assert.ok(eigen.value.every((value, i) => Math.abs(value - [1, 3][i]) < 1e-10));
assert.ok(eigen.residualInfNorm < 1e-10 && eigen.offDiagonalNorm <= 1e-12);
assert.equal(N.symmetricEigen([[1, 2], [3, 4]]).status, "invalid-input");
const sensitivity = ok(N.linearSensitivity([[1, 0], [0, 2]], [1, 2], { b: [0.01, 0] }));
assert.ok(Math.abs(sensitivity.value.delta[0] - 0.01) < 1e-12);
assert.ok(Number.isFinite(sensitivity.conditionBasedRelativeEstimate));
assert.match(linear.sensitivity.semantics, /not an unconditional error bound/);
assert.ok(Number.isFinite(linear.sensitivity.residualDerivedRelativeErrorEstimate));
let state = 0x9e3779b9;
const random = () => { state ^= state << 13; state ^= state >>> 17; state ^= state << 5; return (state >>> 0) / 4294967296; };
for (let trial = 0; trial < 100; trial++) {
  const A = Array.from({ length: 4 }, (_, i) => Array.from({ length: 4 }, (_, j) => i === j ? 4 + random() : random() - 0.5));
  const b = Array.from({ length: 4 }, random);
  const result = ok(N.solveLinear(A, b));
  assert.ok(result.residualInfNorm < 1e-10);
}
